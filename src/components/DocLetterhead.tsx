"use client";

/**
 * หัวกระดาษ + คำเตือน + ข้อความกำกับ ของเอกสารที่พิมพ์จากหน้าเว็บ
 * ---------------------------------------------------------------------------
 * QA BUG-046 (Critical)
 *
 * กติกาของไฟล์นี้:
 *   1. ห้ามพิมพ์ชื่อบริษัท/เลขผู้เสียภาษีที่แต่งขึ้นเด็ดขาด — ไม่รู้ต้องบอกว่าไม่รู้
 *   2. คำเตือนต้องเห็นทั้งบนจอ **และตอนสั่งพิมพ์** (ห้ามอยู่ใน @media screen อย่างเดียว
 *      และห้ามติด class .no-print) เพราะความเสี่ยงอยู่ที่กระดาษที่คนเอาไปเซ็น
 *   3. ระหว่างยังโหลดโปรไฟล์ไม่เสร็จ ห้ามพิมพ์หัวกระดาษออกมาแวบหนึ่ง —
 *      ถ้าผู้ใช้กด Ctrl+P ตอนนั้น กระดาษต้องไม่ติดค่าที่ยังไม่ยืนยันไปด้วย
 *   4. ทั้ง 4 หน้าเอกสารใช้คอมโพเนนต์ชุดนี้ร่วมกัน จะได้ไม่มีหน้าไหนเงียบ
 *
 * ทั้งหมดนี้ **ไม่ได้** ตัดสินว่ารูปแบบเอกสารถูกหรือผิด — นั่นคือ Q-2 ที่ยังเปิดอยู่
 */

import type { Letterhead } from "@/lib/company";
import { NOT_SET } from "@/lib/company";
import { bangkokToday } from "@/lib/date";

/** ค่าที่ยังไม่มี → แสดงเครื่องหมายที่อ่านออกว่าไม่ใช่ข้อมูลจริง ไม่ใช่ตัวเลขที่แต่งขึ้น */
function shown(value: string): string {
  return value.trim() || NOT_SET;
}

export function DocLetterhead({ head }: { head: Letterhead }) {
  // ---- 3. ระหว่างโหลด: ไม่พิมพ์หัวกระดาษใด ๆ ออกมา ----
  if (head.loading) {
    return (
      <>
        <div className="doc-head doc-head-pending">
          <div className="doc-company">{NOT_SET}</div>
          <div className="doc-company-sub">กำลังอ่านโปรไฟล์บริษัท…</div>
        </div>
        <div className="doc-warn" role="status">
          ⚠ ยังอ่านโปรไฟล์บริษัทไม่เสร็จ — <strong>ห้ามสั่งพิมพ์หรือลงนามเอกสารฉบับนี้ตอนนี้</strong>
          <div>รอให้หัวกระดาษด้านบนแสดงชื่อบริษัทจริงก่อน แล้วจึงสั่งพิมพ์ใหม่</div>
        </div>
      </>
    );
  }

  return (
    <>
      <div className={`doc-head${head.isFallback ? " doc-head-pending" : ""}`}>
        <div className="doc-company">{shown(head.name)}</div>
        <div className="doc-company-sub">{shown(head.address)}</div>
        <div className="doc-company-sub">
          โทร. {shown(head.phone)} · เลขประจำตัวผู้เสียภาษี {shown(head.taxId)}
        </div>
      </div>

      {/* ---- 1 + 2: คำเตือนอยู่ติดหัวกระดาษ และพิมพ์ติดกระดาษไปด้วยเสมอ ----
           ข้อความแยกตามสาเหตุจริง: "ไม่มีสิทธิ์อ่าน" ไม่ใช่เรื่องเดียวกับ "ยังไม่ได้ตั้งค่า"
           การเขียนว่าบริษัทยังไม่ตั้งค่าทั้งที่จริง ๆ แค่บัญชีนี้อ่านไม่ได้ คือการกล่าวหาผิด
           และจะทำให้ผู้ดูแลไปไล่แก้ของที่ไม่ได้เสีย */}
      {head.isFallback ? (
        <div className="doc-warn" role="alert">
          {head.gap === "forbidden" ? (
            <>
              ⚠ <strong>บัญชีนี้ไม่มีสิทธิ์อ่านโปรไฟล์บริษัท</strong> จึงยังไม่มีหัวกระดาษบนเอกสารฉบับนี้
              <div>
                ข้อมูลบริษัทอาจตั้งค่าไว้ครบแล้ว — ระบบเพียงแต่ไม่แสดงให้บัญชีนี้
                ช่องที่ขึ้นว่า “{NOT_SET}” คือค่าที่<strong>บัญชีนี้</strong>ยังไม่เห็น ไม่ใช่ค่าที่ไม่มีอยู่
                <br />
                <strong>ห้ามนำเอกสารฉบับนี้ไปใช้ลงนามหรือยื่นทางภาษี</strong> —
                ให้ผู้ที่มีสิทธิ์ออกเอกสารเป็นผู้เปิดและสั่งพิมพ์แทน
              </div>
            </>
          ) : head.gap === "error" ? (
            <>
              ⚠ <strong>อ่านโปรไฟล์บริษัทไม่สำเร็จ</strong> (ระบบหรือเครือข่ายขัดข้อง)
              <div>
                ช่องที่ขึ้นว่า “{NOT_SET}” คือค่าที่ระบบยังอ่านไม่ได้ ไม่ใช่ค่าที่ไม่มีอยู่ —
                ระบบจะไม่เติมชื่อบริษัทหรือเลขประจำตัวผู้เสียภาษีให้เอง
                <br />
                <strong>ห้ามนำเอกสารฉบับนี้ไปใช้ลงนามหรือยื่นทางภาษี</strong> — โหลดหน้าใหม่แล้วลองอีกครั้ง
              </div>
            </>
          ) : (
            <>
              ⚠ เอกสารฉบับนี้<strong>ยังไม่มีข้อมูลบริษัท</strong> — ยังไม่ได้ตั้งค่าโปรไฟล์บริษัทไว้
              <div>
                ช่องที่ขึ้นว่า “{NOT_SET}” คือค่าที่ระบบยังไม่ทราบ
                ระบบจะไม่เติมชื่อบริษัทหรือเลขประจำตัวผู้เสียภาษีให้เอง —
                <strong>ห้ามนำเอกสารฉบับนี้ไปใช้ลงนามหรือยื่นทางภาษี</strong>
                จนกว่าผู้ดูแลจะตั้งค่าที่ ตั้งค่า &gt; โปรไฟล์บริษัท
              </div>
            </>
          )}
        </div>
      ) : head.missing.length > 0 ? (
        <div className="doc-warn" role="alert">
          ⚠ โปรไฟล์บริษัทยังไม่ครบ — ยังขาด: {head.missing.join(" · ")}
          <div>ตรวจสอบที่ ตั้งค่า &gt; โปรไฟล์บริษัท ก่อนนำเอกสารนี้ไปใช้จริง</div>
        </div>
      ) : null}
    </>
  );
}

/**
 * ข้อความกำกับท้ายเอกสาร — ถ้อยคำตรงกับที่ PDF ฝั่งเซิร์ฟเวอร์พิมพ์ทุกตัวอักษร
 * (`footerNote` ใน routes/jobs.ts · equipment.ts · quotations.ts)
 * เพื่อให้เอกสารสองทางของระบบเดียวกันไม่ได้พูดคนละอย่าง
 */
export function DocApprovalNotice({ head }: { head: Letterhead }) {
  if (head.loading) return null;
  const issued = `ออกโดยระบบ WOMS เมื่อ ${bangkokToday()}`;
  // อ่านโปรไฟล์ไม่ได้ = ถือว่ายังไม่ผ่านการยืนยันเสมอ ไม่เดาว่าอนุมัติแล้ว
  const approved = !head.isFallback && !!head.profile?.approved;
  return (
    <p className="doc-note" role="status">
      {approved
        ? issued
        : `${issued} — หัวเอกสารนี้ยังไม่ได้รับการยืนยันว่าตรงกับแบบฟอร์มที่บริษัทอนุมัติ`}
    </p>
  );
}
